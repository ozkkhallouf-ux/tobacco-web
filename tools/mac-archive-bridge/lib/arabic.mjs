// تطبيع النصوص العربية لمطابقة أسماء المجلدات على iCloud Drive.
//
// السبب الجذري: أسماء المجلدات العربية على macOS لا تُخزَّن بصيغة واحدة.
// قياس فعلي على جهاز المالك (2026-08-31):
//   «فواتير الزبائن»    -> مخزَّن NFD: الهمزة محرف مركّب U+0654 بعد الياء
//   «نشرات أسعار»       -> مخزَّن NFD: الألف + U+0654 بدل U+0623
//   «فواتير المشتريات»  -> يبدأ بمحرف U+200F (RLM) مخفي تماماً بصرياً
// لذلك أي hardcoded path أو مقارنة نصية مباشرة تفشل بصمت. نطبّع الطرفين
// (اسم المجلد على القرص + الاسم المتوقع) إلى صيغة واحدة قبل المقارنة.

// محارف تحكّم/اتجاه غير مرئية تظهر داخل أسماء أنشأها Finder أو نُسخت من واتساب،
// إضافة إلى التطويل (U+0640) الذي يمدّ الحرف بصرياً بلا تغيير المعنى.
const INVISIBLE = /[​-‏؜⁦-⁩‪-‮﻿ـ]/g;

// التشكيل والحركات — لا تُغيّر معنى الاسم لكنها تكسر المطابقة.
const DIACRITICS = /[ً-ْٰٖٜٟٗ٘ٙٚٛٝٞۖ-ۭ]/g;

/** يحذف المحارف غير المرئية والتشكيل من نص عربي. */
export function stripInvisible(value) {
  return String(value == null ? "" : value).replace(INVISIBLE, "").replace(DIACRITICS, "");
}

/**
 * مفتاح مطابقة موحّد: NFC ثم حذف غير المرئي ثم توحيد صور الألف/الياء/الهاء
 * ثم طيّ المسافات. يُستعمل للمقارنة فقط — لا يُكتب به أي اسم ملف.
 *
 * ملاحظة: حذف U+0654 يتم ضمناً بـNFC (ي + U+0654 -> U+0626) ثم بتوحيد الياء.
 */
export function folderKey(value) {
  return stripInvisible(String(value == null ? "" : value).normalize("NFC"))
    .replace(/[آأإٱ]/g, "ا") // آ أ إ ٱ -> ا
    .replace(/ؤ/g, "و")                     // ؤ -> و
    .replace(/[ئى]/g, "ي")             // ئ ى -> ي
    .replace(/ة/g, "ه")                     // ة -> ه
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}
