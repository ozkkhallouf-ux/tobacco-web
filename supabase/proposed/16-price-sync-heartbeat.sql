--   d) trigger tg_notify_inventory_report يطلق «📦 وصل تقرير الجرد» عند
--      أول إدراج يومي لأي مصدر. هذا الجدول لا يحمل أي trigger.
--   ولا يغيّر هذا الملف ameen_price_sync_status ولا المراقب
