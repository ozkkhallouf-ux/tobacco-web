do $$
begin
  if not exists (
    select 1 from pg_catalog.pg_proc p
    join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    where p.proname = 'is_staff' and n.nspname = 'public'
  ) then
    raise exception
      'أوقفت التنفيذ: الدالة public.is_staff() غير موجودة، وسياسة القراءة تعتمد عليها.';
  end if;
end
$$;

create table if not exists public.price_sync_heartbeat (
  id bigint generated by default as identity primary key,
  -- ok: سحب + تطبيق + تحقق مطابق. mismatch: التحقق وجد فروقاً أو نواقص.
  -- pull_failed / apply_failed / verify_failed: فشل في تلك الخطوة.
  -- disabled / paused: يبلّغ بها طرف خارجي (الحارس أو إجراء صيانة رسمي).
  status text not null check (status in (
    'ok', 'mismatch', 'pull_failed', 'apply_failed', 'verify_failed', 'disabled', 'paused'
  )),
  stage text not null check (stage in ('pull', 'apply', 'verify', 'done', 'external')),
  attempt_started_at timestamptz,
  attempt_finished_at timestamptz,
  computer text,
  pulled_count integer not null default 0 check (pulled_count >= 0),
  feed_max_updated_at timestamptz,
  applied_wholesale integer not null default 0 check (applied_wholesale >= 0),
  applied_retail integer not null default 0 check (applied_retail >= 0),
  skipped_count integer not null default 0 check (skipped_count >= 0),
  not_found_count integer not null default 0 check (not_found_count >= 0),
  conflict_count integer not null default 0 check (conflict_count >= 0),
  verified_wholesale integer not null default 0 check (verified_wholesale >= 0),
  verified_retail integer not null default 0 check (verified_retail >= 0),
  mismatch_count integer not null default 0 check (mismatch_count >= 0),
  missing_count integer not null default 0 check (missing_count >= 0),
  message text not null default '' check (length(message) <= 500),
  -- محسوبة في الدالة على ساعة الخادم (تُحمَل من الصف السابق عند غياب الحدث):
  ameen_connected_at timestamptz,
  last_applied_at timestamptz,
  applied_feed_max_updated_at timestamptz,
  last_success_at timestamptz,
  last_failure_at timestamptz,
  last_failure_status text,
  new_prices boolean,
  previous_status text,
  gap_minutes numeric,
  created_by uuid not null default auth.uid(),
  created_at timestamptz not null default now()
);

create index if not exists price_sync_heartbeat_created_at_idx
  on public.price_sync_heartbeat (created_at desc);

alter table public.price_sync_heartbeat enable row level security;
alter table public.price_sync_heartbeat force row level security;

revoke all on public.price_sync_heartbeat from public, anon, authenticated;
grant select on public.price_sync_heartbeat to authenticated;
-- service_role يبقى على صلاحياته الافتراضية (قراءة دوال Telegram لاحقاً).

drop policy if exists "staff can read price sync heartbeat" on public.price_sync_heartbeat;
create policy "staff can read price sync heartbeat"
  on public.price_sync_heartbeat for select
  to authenticated
  using (public.is_staff());
-- لا سياسة INSERT/UPDATE/DELETE: الكتابة عبر الدالة أدناه وحدها.

create or replace function public.record_price_sync_heartbeat(p_heartbeat jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_status text := p_heartbeat->>'status';
  v_stage text := coalesce(nullif(p_heartbeat->>'stage', ''), 'external');
  v_connected boolean := coalesce((p_heartbeat->>'ameen_connected')::boolean, false);
  v_applied boolean := coalesce((p_heartbeat->>'applied')::boolean, false);
  v_feed_max timestamptz := nullif(p_heartbeat->>'feed_max_updated_at', '')::timestamptz;
  v_conflicts integer := coalesce((p_heartbeat->>'conflict_count')::integer, 0);
  v_prev public.price_sync_heartbeat%rowtype;
  v_now timestamptz := pg_catalog.now();
  v_is_failure boolean;
  v_success boolean;
  v_row public.price_sync_heartbeat%rowtype;
begin
  -- هوية المزامنة الموثوقة نفسها التي تكتب تقارير الأمين وتدقيق خليل.
  if (select auth.uid()) is distinct from '9724dbe4-ecb0-49f7-a6b4-12f7f73c68f3'::uuid then
    raise exception 'record_price_sync_heartbeat is restricted to the trusted sync identity'
      using errcode = '42501';
  end if;
  if p_heartbeat is null or pg_catalog.jsonb_typeof(p_heartbeat) <> 'object' then
    raise exception 'heartbeat must be a json object' using errcode = '22023';
  end if;
  if v_status is null or v_status not in (
    'ok', 'mismatch', 'pull_failed', 'apply_failed', 'verify_failed', 'disabled', 'paused'
  ) then
    raise exception 'unknown heartbeat status: %', coalesce(v_status, '<null>') using errcode = '22023';
  end if;
  -- ok بلا تطبيق أو بلا اتصال بالأمين تناقض: لا نسجّله نجاحاً.
  if v_status = 'ok' and not (v_applied and v_connected) then
    raise exception 'ok heartbeat must report applied=true and ameen_connected=true' using errcode = '22023';
  end if;

  -- تسلسل الكتّاب: الحساب من الصف السابق يجب ألا يتسابق.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('public.price_sync_heartbeat'));

  select * into v_prev from public.price_sync_heartbeat order by created_at desc, id desc limit 1;

  v_is_failure := v_status in ('mismatch', 'pull_failed', 'apply_failed', 'verify_failed');
  -- النجاح المثبت: تطبيق + تحقق مطابق + صفر تعارض.
  v_success := v_status = 'ok' and v_conflicts = 0;

  insert into public.price_sync_heartbeat (
    status, stage, attempt_started_at, attempt_finished_at, computer,
    pulled_count, feed_max_updated_at,
    applied_wholesale, applied_retail, skipped_count, not_found_count, conflict_count,
    verified_wholesale, verified_retail, mismatch_count, missing_count, message,
    ameen_connected_at, last_applied_at, applied_feed_max_updated_at,
    last_success_at, last_failure_at, last_failure_status,
    new_prices, previous_status, gap_minutes
  ) values (
    v_status, v_stage,
    nullif(p_heartbeat->>'attempt_started_at', '')::timestamptz,
    nullif(p_heartbeat->>'attempt_finished_at', '')::timestamptz,
    left(nullif(p_heartbeat->>'computer', ''), 100),
    coalesce((p_heartbeat->>'pulled_count')::integer, 0),
    v_feed_max,
    coalesce((p_heartbeat->>'applied_wholesale')::integer, 0),
    coalesce((p_heartbeat->>'applied_retail')::integer, 0),
    coalesce((p_heartbeat->>'skipped_count')::integer, 0),
    coalesce((p_heartbeat->>'not_found_count')::integer, 0),
    v_conflicts,
    coalesce((p_heartbeat->>'verified_wholesale')::integer, 0),
    coalesce((p_heartbeat->>'verified_retail')::integer, 0),
    coalesce((p_heartbeat->>'mismatch_count')::integer, 0),
    coalesce((p_heartbeat->>'missing_count')::integer, 0),
    left(coalesce(p_heartbeat->>'message', ''), 500),
    case when v_connected then v_now else v_prev.ameen_connected_at end,
    case when v_applied then v_now else v_prev.last_applied_at end,
    case when v_applied then v_feed_max else v_prev.applied_feed_max_updated_at end,
    case when v_success then v_now else v_prev.last_success_at end,
    case when v_is_failure then v_now else v_prev.last_failure_at end,
    case when v_is_failure then v_status else v_prev.last_failure_status end,
    -- هل وصل سعر جديد منذ آخر تطبيق؟ null = لا يمكن الحكم.
    case
      when not v_applied or v_feed_max is null then null
      when v_prev.applied_feed_max_updated_at is null then true
      else v_feed_max > v_prev.applied_feed_max_updated_at
    end,
    v_prev.status,
    case when v_prev.created_at is null then null
         else round(extract(epoch from (v_now - v_prev.created_at)) / 60.0, 1) end
  )
  returning * into v_row;

  -- احتفاظ 14 يوماً: نحو 4,000 صف بإيقاع 5 دقائق.
  delete from public.price_sync_heartbeat where created_at < v_now - interval '14 days';

  return pg_catalog.jsonb_build_object(
    'ok', true,
    'id', v_row.id,
    'status', v_row.status,
    'last_success_at', v_row.last_success_at,
    'ameen_connected_at', v_row.ameen_connected_at
  );
end;
$$;

revoke all on function public.record_price_sync_heartbeat(jsonb) from public, anon, authenticated;
grant execute on function public.record_price_sync_heartbeat(jsonb) to authenticated;

notify pgrst, 'reload schema';
