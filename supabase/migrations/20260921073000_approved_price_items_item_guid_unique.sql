-- قيد فريد على هوية بطاقة الأمين في approved_price_items.
--
-- لماذا: حارس منع الازدواج يعمل في المتصفح بين SELECT وupsert منفصلين، فبين
-- الفحص والكتابة نافذة TOCTOU حقيقية — تبويبان (أو جهازان) يحفظان مفتاحين
-- مختلفين لنفس البطاقة يمرّان كلاهما من الفحص وينجح الاثنان، فتعود صفوف
-- item_guid المكررة رغم الحارس. القيد هنا هو خط الدفاع الأخير الذي يجعل
-- الكتابة الثانية تفشل بدل أن تُنشئ مكرراً. (Codex P1 على PR #257.)
--
-- لماذا على upper() لا على العمود الخام: الصفوف المخزّنة كلها بأحرف كبيرة
-- (تكتبها tools/pull-item-numbers.ps1 من mt000)، بينما تقرير الجرد الحي
-- يسلّم itemGuid بأحرف صغيرة — وهو المصدر الذي صار مسار الحفظ يثبّت منه هوية
-- الصف الجديد. فقيدٌ على العمود الخام كان سيسمح بتعايش 'abc…' و'ABC…'، أي
-- يسقط بالضبط في الحالة التي وُجد ليمنعها. قياس وقت الإنشاء: 313 صفاً مخزّناً
-- بأحرف كبيرة مقابل 441 بطاقة حية بأحرف صغيرة.
--
-- شرط جزئي على IS NOT NULL: الصفوف بلا هوية لا تتزاحم على القيد. (وقت الإنشاء
-- لم يكن هناك أي صف كهذا — 0 من 313 — لكن الشرط يبقى صحيحاً بنيوياً.)
--
-- الفهرس غير الفريد idx_approved_price_items_item_guid يبقى كما هو للبحث
-- بالهوية الخام؛ هذا القيد لا يخدم الاستعلام بل يمنع الحالة المستحيلة.
--
-- متطلّب مسبق: لا صفوف مكررة الهوية. أُنجز تنظيف الـ72 مفتاحاً الميتاً
-- وbackfill الهويات الفارغة قبل هذا القيد (2026-09-21)، فصارت 313 صفاً =
-- 313 هوية مميزة = صفر فارغ.

create unique index if not exists approved_price_items_item_guid_unique
  on public.approved_price_items (upper(item_guid))
  where item_guid is not null;
